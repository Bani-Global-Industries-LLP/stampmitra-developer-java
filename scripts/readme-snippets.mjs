#!/usr/bin/env node
// Turns every ```java block of README.md into a compiled method in examples/.../ReadmeSnippets.java, so a snippet that
// no longer compiles against the SDK fails the examples build.
//
//   node scripts/readme-snippets.mjs           regenerate the file
//   node scripts/readme-snippets.mjs --check   fail if it is out of date
//
// Snippet blocks are statement-level code: leading `import` lines are hoisted, and the variables `client`, `secret`,
// `rawBody`, `timestamp` and `signature` are supplied as method parameters unless the snippet declares them itself.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const readme = readFileSync(resolve(root, "README.md"), "utf8");
const target = resolve(root, "examples/src/main/java/in/stampmitra/examples/ReadmeSnippets.java");

const blocks = [...readme.matchAll(/```java\n([\s\S]*?)```/g)].map((m) => m[1]);
const imports = new Set(["in.stampmitra.sdk.StampMitra"]);
const supplied = {
  client: "StampMitra client",
  secret: "String secret",
  rawBody: "String rawBody",
  timestamp: "String timestamp",
  signature: "String signature",
};

const methods = blocks.map((block, i) => {
  const body = [];
  for (const line of block.split("\n")) {
    const m = line.match(/^import (static )?([\w.*]+);$/);
    if (m) imports.add((m[1] ?? "") + m[2]);
    else body.push(line);
  }
  const text = body.join("\n").replace(/^\n+|\n+$/g, "");
  const params = Object.entries(supplied)
    .filter(([name]) => new RegExp(`\\b${name}\\b`).test(text) && !new RegExp(`\\b(StampMitra|String)\\s+${name}\\b`).test(text))
    .map(([, decl]) => decl);
  const indented = text.split("\n").map((l) => (l ? "        " + l : l)).join("\n");
  return `    static void snippet${i + 1}(${params.join(", ")}) throws Exception {\n${indented}\n    }\n`;
});

const out = `// Generated by scripts/readme-snippets.mjs from the java blocks of README.md. Do not edit by hand.
package in.stampmitra.examples;

${[...imports].sort().map((i) => `import ${i};`).join("\n")}

/** Compile check for the README snippets: never run, only compiled (${blocks.length} snippets). */
final class ReadmeSnippets {

    private ReadmeSnippets() {
    }

${methods.join("\n")}}
`;

if (process.argv.includes("--check")) {
  if (!existsSync(target) || readFileSync(target, "utf8") !== out) {
    console.error("examples/.../ReadmeSnippets.java is out of date: run node scripts/readme-snippets.mjs");
    process.exit(1);
  }
  console.log(`README snippets up to date (${blocks.length})`);
} else {
  writeFileSync(target, out);
  console.log(`wrote ${blocks.length} snippets`);
}
