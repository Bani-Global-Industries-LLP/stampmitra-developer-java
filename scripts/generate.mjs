const constName = (op) =>
  op.http[0] + "_" + op.http[1].replace(/\{(\w+)\}/g, "$1").replace(/[^A-Za-z0-9]+/g, "_").replace(/^_|_$/g, "").toUpperCase();

function genResource(r) {
  const imports = new Set([
    "in.stampmitra.sdk.RequestOptions",
    "in.stampmitra.sdk.internal.Operation",
    "in.stampmitra.sdk.internal.RequestExecutor",
    "java.util.concurrent.CompletableFuture",
  ]);
  const consts = [];
  const methods = [];
  for (const op of r.ops) {
    const cn = constName(op);
    consts.push(`    private static final Operation ${cn} = Operation.${op.http[0].toLowerCase()}("${op.http[1]}");`);
    imports.add(`in.stampmitra.sdk.models.${op.ret}`);
    const path = op.path ?? [];
    const pathSig = path.map((p) => `String ${p.name}`);
    const pathDoc = path.map((p) => `     * @param ${p.name} ${p.doc}`);
    const pathCall = path.map((p) => p.name);

    // argument variants
    let variantsList; // each: { sig: [..], docs: [..], call: [..], kind }
    if (op.body) {
      imports.add(`in.stampmitra.sdk.requests.${op.body}`);
      imports.add("java.util.Map");
      imports.add("java.util.LinkedHashMap");
      variantsList = [
        { argType: op.body, mapType: false },
        { argType: "Map<String, Object>", mapType: true },
      ];
    }
    const idem = op.idem ? "true" : "false";
    const sigOpts = "RequestOptions options";
    const optDoc = "     * @param options per-request overrides (timeout, retries, idempotency key, headers), may be {@code null}";
    const emit = (jsdoc, sig, body) => methods.push(`${jsdoc}${sig} {\n${body}    }\n`);
    const throwsDoc = "     * @throws in.stampmitra.sdk.errors.StampMitraException on API, validation or network errors";

    if (op.body) {
      for (const vr of variantsList) {
        const reqDoc = vr.mapType ? "the request body as a map (unmodelled fields allowed)" : "the request";
        // core: Map version with options
        for (const withOpts of [false, true]) {
          const sig = `public ${op.ret} ${op.name}(${[...pathSig, `${vr.argType} request`, ...(withOpts ? [sigOpts] : [])].join(", ")})`;
          const jsdoc = `    /**\n     * ${op.doc}\n     *\n${[...pathDoc, `     * @param request ${reqDoc}`, ...(withOpts ? [optDoc] : [])].join("\n")}\n     * @return the result\n${throwsDoc}\n     */\n    `;
          let body;
          if (!withOpts) {
            body = `        return ${op.name}(${[...pathCall, "request", "(RequestOptions) null"].join(", ")});\n`;
          } else if (!vr.mapType) {
            body = `        return ${op.name}(${[...pathCall, "Args.required(request, \"request\").toMap()", "options"].join(", ")});\n`;
          } else {
            body = `        Map<String, Object> body = new LinkedHashMap<>(Args.required(request, "request"));\n        if (validateInput) {\n            ${op.body}.validate(body);\n        }\n        return executor.execute(${cn}, ${cn}.render(${pathCall.join(", ")}), null, body, options, ${idem}, ${op.ret}::new);\n`;
          }
          emit(jsdoc, sig, body);
        }
        // async twins
        for (const withOpts of [false, true]) {
          const sig = `public CompletableFuture<${op.ret}> ${op.name}Async(${[...pathSig, `${vr.argType} request`, ...(withOpts ? [sigOpts] : [])].join(", ")})`;
          const jsdoc = `    /**\n     * Asynchronous variant of {@link #${op.name}(${[...path.map(() => "String"), vr.argType.replace("<String, Object>", ""), ...(withOpts ? ["RequestOptions"] : [])].join(", ")})}. Failures, including validation errors, complete the future exceptionally;\n     * {@code cancel(true)} interrupts the call.\n     *\n${[...pathDoc, `     * @param request ${reqDoc}`, ...(withOpts ? [optDoc] : [])].join("\n")}\n     * @return a future of the result\n     */\n    `;
          const call = `${op.name}(${[...pathCall, "request", ...(withOpts ? ["options"] : [])].join(", ")})`;
          emit(jsdoc, sig, `        return executor.async(() -> ${call});\n`);
        }
      }
      imports.add("in.stampmitra.sdk.internal.Args");
      continue;
    }

    const args = op.args ?? [];
    const required = args.filter((a) => a.required);
    const sets = [required];
    if (args.length > required.length) sets.push(args);
    const full = sets[sets.length - 1];
    for (const set of sets) {
      for (const withOpts of [false, true]) {
        const params = [...pathSig, ...set.map((a) => `${a.type} ${a.name}`), ...(withOpts ? [sigOpts] : [])];
        const docs = [...pathDoc, ...set.map((a) => `     * @param ${a.name} ${a.doc}`), ...(withOpts ? [optDoc] : [])];
        const isCore = set === full && withOpts;
        const jsdoc = `    /**\n     * ${op.doc}\n     *\n${docs.length ? docs.join("\n") + "\n" : ""}     * @return the result\n${throwsDoc}\n     */\n    `;
        let body;
        if (!isCore) {
          const callArgs = [...pathCall, ...full.map((a) => (set.includes(a) ? a.name : `(${a.type}) null`)), withOpts ? "options" : "(RequestOptions) null"];
          body = `        return ${op.name}(${callArgs.join(", ")});\n`;
        } else {
          body = "";
          const bodyArgs = args.filter((a) => a.in !== "query");
          const queryArgs = args.filter((a) => a.in === "query");
          if (bodyArgs.length) {
            imports.add("java.util.Map");
            imports.add("java.util.LinkedHashMap");
            imports.add("in.stampmitra.sdk.Validators");
            imports.add("in.stampmitra.sdk.internal.Args");
            body += `        Map<String, Object> body = new LinkedHashMap<>();\n`;
            for (const a of bodyArgs) {
              if (a.required) {
                body += `        body.put("${a.json}", validateInput ? ${a.validate(a.name)} : Args.required(${a.name}, "${a.json}"));\n`;
              } else {
                body += `        if (${a.name} != null) {\n            body.put("${a.json}", validateInput ? ${a.validate(a.name)} : ${a.name});\n        }\n`;
              }
            }
          }
          if (queryArgs.length) {
            imports.add("java.util.Map");
            imports.add("java.util.LinkedHashMap");
            body += `        Map<String, String> query = new LinkedHashMap<>();\n`;
            for (const a of queryArgs) body += `        if (${a.name} != null) {\n            query.put("${a.json}", String.valueOf(${a.name}));\n        }\n`;
          }
          const renderArgs = pathCall.join(", ");
          body += `        return executor.execute(${cn}, ${cn}.render(${renderArgs}), ${queryArgs.length ? "query" : "null"}, ${bodyArgs.length ? "body" : "null"}, options, ${idem}, ${op.ret}::new);\n`;
        }
        emit(jsdoc, `    public ${op.ret} ${op.name}(${params.join(", ")})`.replace(/^ {4}/, ""), body);

        // async twin
        const aparams = params;
        const ajsdoc = `    /**\n     * Asynchronous variant of {@link #${op.name}(${[...path.map(() => "String"), ...set.map((a) => a.type), ...(withOpts ? ["RequestOptions"] : [])].join(", ")})}. Failures, including validation errors, complete the future exceptionally;\n     * {@code cancel(true)} interrupts the call.\n     *\n${docs.length ? docs.join("\n") + "\n" : ""}     * @return a future of the result\n     */\n    `;
        const acall = `${op.name}(${[...pathCall, ...set.map((a) => a.name), ...(withOpts ? ["options"] : [])].join(", ")})`;
        emit(ajsdoc, `public CompletableFuture<${op.ret}> ${op.name}Async(${aparams.join(", ")})`, `        return executor.async(() -> ${acall});\n`);
      }
    }
  }
  let out = `${HEADER}package ${PKG}.resources;\n\n`;
  out += [...imports].sort().map((i) => `import ${i};`).join("\n") + "\n\n";
  out += `/**\n * ${r.doc.replace(/`([^`]+)`/g, "{@code $1}")}\n */\npublic final class ${r.cls} {\n\n`;
  out += consts.join("\n") + "\n\n";
  out += `    private final RequestExecutor executor;\n    private final boolean validateInput;\n\n`;
  out += `    /**\n     * Creates the resource. Use the accessor on {@link in.stampmitra.sdk.StampMitra} instead.\n     *\n     * @param executor      the shared request executor\n     * @param validateInput whether to validate inputs locally before sending\n     */\n    public ${r.cls}(RequestExecutor executor, boolean validateInput) {\n        this.executor = executor;\n        this.validateInput = validateInput;\n    }\n\n`;
  out += methods.join("\n");
  out += "}\n";
  files.set(resolve(outDir("resources"), `${r.cls}.java`), out);
}
for (const r of resources) genResource(r);

// ---------------------------------------------------------------- write / check
let stale = 0;
for (const [path, content] of files) {
  if (check) {
    const current = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (current !== content) {
      console.error(`stale or missing: ${path}`);
      stale++;
    }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
}
if (check) {
  if (stale) {
    console.error(`${stale} generated file(s) out of date: run node scripts/generate.mjs`);
    process.exit(1);
  }
  console.log(`generated sources up to date (${files.size} files)`);
} else {
  console.log(`generated ${files.size} files`);
}
