function genRequest(schemaName, cls) {
  const s = schemas[schemaName];
  const req = new Set(s.required ?? []);
  const props = Object.entries(s.properties);
  const imports = new Set(["in.stampmitra.sdk.errors.ValidationException", "java.util.Collections", "java.util.LinkedHashMap", "java.util.Map"]);
  const setters = [];
  const checks = [];
  for (const [k, p] of props) {
    const t = primaryType(p);
    const doc = p.description ? esc(p.description) : `Sets {@code ${k}}.`;
    let type;
    if (t === "string") type = "String";
    else if (t === "integer") type = "Long";
    else if (t === "number") {
      type = "BigDecimal";
      imports.add("java.math.BigDecimal");
    } else if (t === "boolean") type = "Boolean";
    else type = "Map<String, Object>";
    setters.push({ k, type, doc, t });
    const present = req.has(k)
      ? `        if (!body.containsKey("${k}") || body.get("${k}") == null${type === "String" ? ` || String.valueOf(body.get("${k}")).trim().isEmpty()` : ""}) {\n            throw new ValidationException("${k}", "${k} is required");\n        }\n`
      : "";
    let len = "";
    if (type === "String" && (p.minLength !== undefined || p.maxLength !== undefined)) {
      const conds = [];
      if (p.minLength !== undefined) conds.push(`String.valueOf(body.get("${k}")).length() < ${p.minLength}`);
      if (p.maxLength !== undefined) conds.push(`String.valueOf(body.get("${k}")).length() > ${p.maxLength}`);
      const range = p.maxLength !== undefined ? `${p.minLength ?? 0}-${p.maxLength}` : `at least ${p.minLength}`;
      len = `        if (body.get("${k}") != null && (${conds.join(" || ")})) {\n            throw new ValidationException("${k}", "${k} must be ${range} characters");\n        }\n`;
    }
    checks.push(present + len);
  }
  const desc = esc(s.description ?? `Request body of the {@code ${schemaName}} operation.`);
  let out = `${HEADER}package ${PKG}.requests;\n\n`;
  out += [...imports].sort().map((i) => `import ${i};`).join("\n") + "\n\n";
  out += `/**\n * ${desc}\n *\n * <p>Immutable; build with {@link #builder()}. Methods that take this type also accept a plain {@code Map} for fields\n * not modelled here.\n */\npublic final class ${cls} {\n\n`;
  out += `    private final Map<String, Object> fields;\n\n    private ${cls}(Map<String, Object> fields) {\n        this.fields = Collections.unmodifiableMap(fields);\n    }\n\n`;
  out += `    /**\n     * Starts a builder.\n     *\n     * @return a new builder\n     */\n    public static Builder builder() {\n        return new Builder();\n    }\n\n`;
  out += `    /**\n     * The JSON body as a map (fields that were not set are omitted).\n     *\n     * @return an unmodifiable map\n     */\n    public Map<String, Object> toMap() {\n        return fields;\n    }\n\n`;
  out += `    /**\n     * Checks the documented constraints (required fields, lengths) of a request body.\n     *\n     * @param body the body to check\n     * @throws ValidationException if a constraint is violated\n     */\n    public static void validate(Map<String, Object> body) {\n${checks.join("") || ""}    }\n\n`;
  out += `    @Override\n    public String toString() {\n        return "${cls}" + fields.keySet();\n    }\n\n`;
  out += `    /** Builder for {@link ${cls}}. */\n    public static final class Builder {\n\n        private final Map<String, Object> fields = new LinkedHashMap<>();\n\n        private Builder() {\n        }\n`;
  for (const { k, type, doc, t } of setters) {
    out += `\n        /**\n         * ${doc}\n         *\n         * @param value the value\n         * @return this builder\n         */\n        public Builder ${k}(${type} value) {\n            put("${k}", value);\n            return this;\n        }\n`;
    if (t === "number") {
      out += `\n        /**\n         * Sets {@code ${k}} from a double.\n         *\n         * @param value the value\n         * @return this builder\n         */\n        public Builder ${k}(double value) {\n            return ${k}(BigDecimal.valueOf(value));\n        }\n`;
    }
    if (t === "integer") {
      out += `\n        /**\n         * Sets {@code ${k}} from a primitive long.\n         *\n         * @param value the value\n         * @return this builder\n         */\n        public Builder ${k}(long value) {\n            return ${k}(Long.valueOf(value));\n        }\n`;
    }
  }
  out += `\n        private void put(String key, Object value) {\n            if (value == null) {\n                fields.remove(key);\n            } else {\n                fields.put(key, value);\n            }\n        }\n\n`;
  out += `        /**\n         * Builds the immutable request. Required fields are checked when the request is sent.\n         *\n         * @return the request\n         */\n        public ${cls} build() {\n            return new ${cls}(new LinkedHashMap<>(fields));\n        }\n    }\n}\n`;
  files.set(resolve(outDir("requests"), `${cls}.java`), out);
}
