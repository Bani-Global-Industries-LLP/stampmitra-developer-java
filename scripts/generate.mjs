function modelProp(key, prop, required) {
  const base = getterBase(key);
  const doc = prop.description ? esc(prop.description) : `The {@code ${key}} field.`;
  const ref = refName(prop);
  const t = primaryType(prop);
  let type;
  let expr;
  let name = `get${base}`;
  let ret = `the {@code ${key}} field, or {@code null} when absent`;
  if (ref && MODEL_NAMES[ref]) {
    type = MODEL_NAMES[ref];
    expr = `model("${key}", ${type}::new)`;
  } else if (t === "string" && prop.format === "date-time") {
    type = "Instant";
    expr = `instant("${key}")`;
    ret += " or not ISO-8601";
  } else if (t === "string") {
    type = "String";
    expr = `string("${key}")`;
  } else if (t === "boolean") {
    const isPrefixed = /^is[A-Z]/.test(key);
    if (isPrefixed) name = key;
    if (required) {
      type = "boolean";
      if (!isPrefixed) name = `is${base}`;
      expr = `bool("${key}")`;
      ret = `the {@code ${key}} flag ({@code false} when the field is absent)`;
    } else {
      type = "Boolean";
      expr = `boolOrNull("${key}")`;
    }
  } else if (t === "integer") {
    type = "Long";
    expr = `longValue("${key}")`;
  } else if (t === "number") {
    type = "BigDecimal";
    expr = `decimal("${key}")`;
  } else if (t === "array") {
    const itemRef = prop.items ? refName(prop.items) : null;
    if (itemRef && MODEL_NAMES[itemRef]) {
      type = `List<${MODEL_NAMES[itemRef]}>`;
      expr = `models("${key}", ${MODEL_NAMES[itemRef]}::new)`;
      ret = `the {@code ${key}} entries (empty when absent)`;
    } else {
      type = "List<Map<String, Object>>";
      expr = `mapList("${key}")`;
      ret = `the {@code ${key}} entries (empty when absent)`;
    }
  } else if (t === "object") {
    type = "Map<String, Object>";
    expr = `map("${key}")`;
  } else {
    type = "Object";
    expr = `get("${key}")`;
    ret = `the {@code ${key}} value as decoded JSON (String, Number, Boolean, Map or List), or {@code null}`;
  }
  return { type, name, expr, doc, ret };
}

function genModel(schemaName, cls) {
  const s = schemas[schemaName];
  const props = Object.entries(s.properties ?? {});
  const req = new Set(s.required ?? []);
  const lines = props.map(([k, p]) => modelProp(k, p, req.has(k)));
  const imports = new Set(["in.stampmitra.sdk.ResponseInfo", "java.util.Map"]);
  for (const l of lines) {
    if (l.type.includes("Instant")) imports.add("java.time.Instant");
    if (l.type.includes("BigDecimal")) imports.add("java.math.BigDecimal");
    if (l.type.includes("List<")) imports.add("java.util.List");
  }
  const desc = esc(s.description ?? `The {@code ${schemaName}} response object of the StampMitra API.`);
  let out = `${HEADER}package ${PKG}.models;\n\n`;
  out += [...imports].sort().map((i) => `import ${i};`).join("\n") + "\n\n";
  out += `/**\n * ${desc}\n *\n * <p>Unknown fields are preserved: see {@link #getRaw()} and {@link #get(String)}.\n */\n`;
  out += `public final class ${cls} extends Model {\n\n`;
  out += `    /**\n     * Creates a model without HTTP metadata.\n     *\n     * @param raw the decoded JSON object\n     */\n    public ${cls}(Map<String, Object> raw) {\n        this(raw, null);\n    }\n\n`;
  out += `    /**\n     * Creates a model.\n     *\n     * @param raw      the decoded JSON object\n     * @param response HTTP metadata, may be {@code null}\n     */\n    public ${cls}(Map<String, Object> raw, ResponseInfo response) {\n        super(raw, response);\n    }\n`;
  for (const l of lines) {
    out += `\n    /**\n     * ${l.doc}\n     *\n     * @return ${l.ret}\n     */\n    public ${l.type} ${l.name}() {\n        return ${l.expr};\n    }\n`;
  }
  out += "}\n";
  files.set(resolve(outDir("models"), `${cls}.java`), out);
}
