// ---------------------------------------------------------------- helpers
const esc = (s) =>
  String(s ?? "")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/@/g, "{@literal @}")
    .replace(/\*\//g, "*&#47;");
const cap = (s) => s[0].toUpperCase() + s.slice(1);
const getterBase = (key) => cap(key === key.toUpperCase() ? key.toLowerCase() : key);
const primaryType = (p) => (Array.isArray(p.type) ? p.type.find((t) => t !== "null") : p.type);
const refName = (p) => (p.$ref ? p.$ref.split("/").pop() : null);

