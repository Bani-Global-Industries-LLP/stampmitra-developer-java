let stale = 0;
for (const [path, content] of files) {
  if (check) {
    const current = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (current !== content) {
      console.error(`stale or missing: ${path}`);
      stale++;
    }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
}
if (check) {
  if (stale) {
    console.error(`${stale} generated file(s) out of date: run node scripts/generate.mjs`);
    process.exit(1);
  }
  console.log(`generated sources up to date (${files.size} files)`);
} else {
  console.log(`generated ${files.size} files`);
}
